-- 生产库账户表（表名定死为 T_ACCT，无法修改）
CREATE TABLE T_ACCT (
  ACCT_ID     BIGINT       NOT NULL AUTO_INCREMENT COMMENT '账户ID',
  ACCT_NAME   VARCHAR(100) NOT NULL COMMENT '账户名',
  ACCT_EMAIL  VARCHAR(120) NULL     COMMENT '邮箱',
  CREATE_TIME DATETIME     NULL     COMMENT '创建时间',
  PRIMARY KEY (ACCT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
