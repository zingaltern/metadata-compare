-- 生产 DDL 样例（含若干故意触规项，用于演示比对效果）
-- 注意：生产库只读、网络不可达，实际由 DBA 定时 mysqldump --no-data 导出后 SCP 至输入目录

CREATE TABLE CUSTOMER (
  CUST_ID    BIGINT       NOT NULL AUTO_INCREMENT COMMENT '客户ID',
  客户名      VARCHAR(100) NOT NULL COMMENT '客户姓名',
  CUST_EMAIL VARCHAR(120) NULL     COMMENT '邮箱',
  CREATE_TIME DATETIME     NULL,
  PRIMARY KEY (CUST_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `ORDER` (
  ORDER_ID   BIGINT        NOT NULL COMMENT '订单ID',
  CUST_ID    BIGINT        NOT NULL COMMENT '客户ID',
  ORDER_AMT  DECIMAL(12,2) NOT NULL COMMENT '订单金额',
  ORDER_TIME DATETIME      NULL,
  PRIMARY KEY (ORDER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE PRODUCT (
  PROD_ID      BIGINT        NOT NULL COMMENT '商品ID',
  PROD_NAME    VARCHAR(200)   NOT NULL COMMENT '商品名称',
  PROD_STATUS  VARCHAR(20)    NOT NULL COMMENT '商品状态',
  PRIMARY KEY (PROD_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
